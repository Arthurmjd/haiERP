-- boss（厂长）权限补齐：审批中心/待办中心/采购审批操作 + 财务/工资只读
-- 幂等：INSERT IGNORE，可重复执行。
-- 背景：erp-permissions.sql 对 boss 采用只读白名单（90000~90078 挑 30 个），
--       漏掉审批工作流与财务查看权限，厂长点审批中心/财务页 403。
-- =============================================================================
SET NAMES utf8mb4;

-- 厂长职责内的补充授权：
--   90110 待办中心          90111 审批中心            90126 采购审批（操作按钮）
--   90127 采购驳回          90112 资金总览            90113 应收管理
--   90114 应付管理          90115 收付款              90116 资金流水
--   90121 应收查询          90122 应付查询            90134 期间查询
-- 注：工资单(90024)/工资发放(90123)源脚本有意从 boss 撤销（薪资保密，仅 hr/finance 可见），不补。
INSERT IGNORE INTO sys_role_menu (role_id, menu_id)
SELECT r.role_id, m.menu_id
FROM sys_role r
JOIN sys_menu m ON m.menu_id IN (90110, 90111, 90112, 90113, 90114, 90115, 90116, 90121, 90122, 90126, 90127, 90134)
WHERE r.role_key = 'boss' AND r.del_flag = '0';